use truongphoto_core::AiTier;

/// Maximum number of AI zero-shot tags attached per asset.
pub const MAX_AUTO_TAGS: usize = 8;

/// Returns the calibrated SigLIP2 cosine similarity threshold for zero-shot tagging.
pub const fn tier_tag_threshold(tier: AiTier) -> f32 {
    match tier {
        AiTier::Tier1 => 0.10,
        AiTier::Tier2 => 0.11,
        AiTier::Tier3 => 0.11,
    }
}

